USE DATABASE RETAIL_DW;
CREATE TABLE IF NOT EXISTS RAW.CUSTOMERS_RAW (
  CUSTOMER_ID NUMBER, FIRST_NAME STRING, LAST_NAME STRING,
  EMAIL STRING, CITY STRING, STATE STRING, UPDATED_AT TIMESTAMP_NTZ
);
CREATE TABLE IF NOT EXISTS RAW.PRODUCTS_RAW (
  PRODUCT_ID NUMBER, PRODUCT_NAME STRING, CATEGORY STRING,
  UNIT_PRICE NUMBER(10,2), UPDATED_AT TIMESTAMP_NTZ
);
CREATE TABLE IF NOT EXISTS RAW.ORDERS_RAW (
  ORDER_ID NUMBER, CUSTOMER_ID NUMBER, ORDER_DATE DATE,
  ORDER_STATUS STRING, UPDATED_AT TIMESTAMP_NTZ
);
CREATE TABLE IF NOT EXISTS RAW.ORDER_ITEMS_RAW (
  ORDER_ITEM_ID NUMBER, ORDER_ID NUMBER, PRODUCT_ID NUMBER,
  QUANTITY NUMBER, UNIT_PRICE NUMBER(10,2)
);
