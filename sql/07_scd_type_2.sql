USE DATABASE RETAIL_DW;
CREATE TABLE IF NOT EXISTS CURATED.DIM_CUSTOMER_SCD2 (
  CUSTOMER_ID NUMBER, FIRST_NAME STRING, LAST_NAME STRING, EMAIL STRING,
  CITY STRING, STATE STRING, VALID_FROM TIMESTAMP_NTZ, VALID_TO TIMESTAMP_NTZ,
  IS_CURRENT BOOLEAN
);
-- Step 1: expire current rows whose tracked attributes changed.
UPDATE CURATED.DIM_CUSTOMER_SCD2 tgt
SET VALID_TO = CURRENT_TIMESTAMP(), IS_CURRENT = FALSE
FROM STAGING.CUSTOMERS src
WHERE tgt.CUSTOMER_ID = src.CUSTOMER_ID
  AND tgt.IS_CURRENT = TRUE
  AND (NVL(tgt.EMAIL,'') <> NVL(src.EMAIL,'')
    OR NVL(tgt.CITY,'') <> NVL(src.CITY,'')
    OR NVL(tgt.STATE,'') <> NVL(src.STATE,''));

-- Step 2: insert new customers and changed versions.
INSERT INTO CURATED.DIM_CUSTOMER_SCD2
  (CUSTOMER_ID,FIRST_NAME,LAST_NAME,EMAIL,CITY,STATE,VALID_FROM,VALID_TO,IS_CURRENT)
SELECT src.CUSTOMER_ID,src.FIRST_NAME,src.LAST_NAME,src.EMAIL,src.CITY,src.STATE,
       CURRENT_TIMESTAMP(),NULL,TRUE
FROM STAGING.CUSTOMERS src
LEFT JOIN CURATED.DIM_CUSTOMER_SCD2 tgt
  ON src.CUSTOMER_ID = tgt.CUSTOMER_ID AND tgt.IS_CURRENT = TRUE
WHERE tgt.CUSTOMER_ID IS NULL;
