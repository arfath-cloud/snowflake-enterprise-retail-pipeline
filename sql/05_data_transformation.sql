USE DATABASE RETAIL_DW;
CREATE OR REPLACE VIEW STAGING.CUSTOMERS AS
SELECT CUSTOMER_ID, TRIM(FIRST_NAME) FIRST_NAME, TRIM(LAST_NAME) LAST_NAME,
       LOWER(TRIM(EMAIL)) EMAIL, TRIM(CITY) CITY, UPPER(TRIM(STATE)) STATE,
       UPDATED_AT
FROM RAW.CUSTOMERS_RAW
WHERE CUSTOMER_ID IS NOT NULL;

CREATE OR REPLACE TABLE CURATED.FACT_ORDER_LINES AS
SELECT oi.ORDER_ITEM_ID, o.ORDER_ID, o.CUSTOMER_ID, o.ORDER_DATE,
       oi.PRODUCT_ID, oi.QUANTITY, oi.UNIT_PRICE,
       oi.QUANTITY * oi.UNIT_PRICE AS LINE_TOTAL
FROM RAW.ORDER_ITEMS_RAW oi
JOIN RAW.ORDERS_RAW o ON oi.ORDER_ID = o.ORDER_ID
WHERE oi.QUANTITY > 0 AND oi.UNIT_PRICE >= 0;
