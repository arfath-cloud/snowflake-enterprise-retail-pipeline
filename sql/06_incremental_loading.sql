USE DATABASE RETAIL_DW;
CREATE TABLE IF NOT EXISTS CURATED.DIM_PRODUCT (
  PRODUCT_ID NUMBER, PRODUCT_NAME STRING, CATEGORY STRING,
  UNIT_PRICE NUMBER(10,2), UPDATED_AT TIMESTAMP_NTZ
);
MERGE INTO CURATED.DIM_PRODUCT tgt
USING (
  SELECT PRODUCT_ID, PRODUCT_NAME, CATEGORY, UNIT_PRICE, UPDATED_AT
  FROM RAW.PRODUCTS_RAW
  QUALIFY ROW_NUMBER() OVER (PARTITION BY PRODUCT_ID ORDER BY UPDATED_AT DESC) = 1
) src
ON tgt.PRODUCT_ID = src.PRODUCT_ID
WHEN MATCHED AND src.UPDATED_AT >= tgt.UPDATED_AT THEN UPDATE SET
  PRODUCT_NAME = src.PRODUCT_NAME, CATEGORY = src.CATEGORY,
  UNIT_PRICE = src.UNIT_PRICE, UPDATED_AT = src.UPDATED_AT
WHEN NOT MATCHED THEN INSERT
  (PRODUCT_ID, PRODUCT_NAME, CATEGORY, UNIT_PRICE, UPDATED_AT)
  VALUES (src.PRODUCT_ID, src.PRODUCT_NAME, src.CATEGORY, src.UNIT_PRICE, src.UPDATED_AT);
