USE DATABASE RETAIL_DW;
-- Null business keys
SELECT COUNT(*) AS NULL_CUSTOMER_KEYS FROM RAW.CUSTOMERS_RAW WHERE CUSTOMER_ID IS NULL;
-- Duplicate customer keys
SELECT CUSTOMER_ID, COUNT(*) AS ROW_COUNT
FROM RAW.CUSTOMERS_RAW GROUP BY CUSTOMER_ID HAVING COUNT(*) > 1;
-- Orphan order items
SELECT COUNT(*) AS ORPHAN_ORDER_ITEMS
FROM RAW.ORDER_ITEMS_RAW oi LEFT JOIN RAW.ORDERS_RAW o ON oi.ORDER_ID = o.ORDER_ID
WHERE o.ORDER_ID IS NULL;
-- Negative quantities or prices
SELECT COUNT(*) AS INVALID_ORDER_LINES
FROM RAW.ORDER_ITEMS_RAW WHERE QUANTITY <= 0 OR UNIT_PRICE < 0;
