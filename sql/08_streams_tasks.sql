USE DATABASE RETAIL_DW;
CREATE OR REPLACE STREAM RAW.ORDERS_STREAM ON TABLE RAW.ORDERS_RAW;
CREATE TABLE IF NOT EXISTS CURATED.ORDER_STATUS_AUDIT (
  ORDER_ID NUMBER, CUSTOMER_ID NUMBER, ORDER_STATUS STRING,
  SOURCE_ACTION STRING, CAPTURED_AT TIMESTAMP_NTZ
);
-- Demonstration task. Resume explicitly after reviewing schedule and warehouse costs.
CREATE OR REPLACE TASK CURATED.CAPTURE_ORDER_CHANGES
  WAREHOUSE = RETAIL_WH
  SCHEDULE = '5 MINUTE'
AS
INSERT INTO CURATED.ORDER_STATUS_AUDIT
SELECT ORDER_ID, CUSTOMER_ID, ORDER_STATUS, METADATA$ACTION, CURRENT_TIMESTAMP()
FROM RAW.ORDERS_STREAM;
